"""Run retrieval evaluation for dense, bm25 and hybrid retrievers.

Usage: python scripts/run_retrieval_eval.py
"""
from __future__ import annotations

import json
import os
from pathlib import Path
from typing import List

from src.eval.retrieval_eval import evaluate_retriever, load_eval_file
from src.retrieval.bm25 import BM25Store
from src.retrieval.dense import dense_search, embed_texts
from src.retrieval.hybrid import hybrid_search


def _load_or_build_bm25(index_path: str = "data/bm25_index.json") -> BM25Store:
    store = BM25Store()
    p = Path(index_path)
    if p.exists():
        store.load(str(p))
        return store

    # Build simple BM25 from raw md files as fallback
    from src.eval.generate_qa import _read_md_files, _extract_text

    files = _read_md_files("data/raw")
    docs = []
    for i, fp in enumerate(files):
        text = _extract_text(fp)
        if not text:
            continue
        docs.append({"id": fp.as_posix(), "text": text, "source_file": fp.as_posix(), "heading": ""})
    store.build(docs)
    store.save(index_path)
    return store


def _bm25_fn_factory(store: BM25Store):
    def fn(q: str, top_k: int = 5):
        return store.search(q, top_k=top_k)

    return fn


def _dense_fn_wrapper():
    def fn(q: str, top_k: int = 5):
        return dense_search(q, top_k=top_k)

    return fn


def main():
    eval_path = Path("data/eval_qa.jsonl")
    if not eval_path.exists():
        print("Eval dataset not found at data/eval_qa.jsonl. Run src/eval/generate_qa.py or make gen-eval")
        return

    eval_data = load_eval_file(str(eval_path))
    bm25_store = _load_or_build_bm25()

    bm25_fn = _bm25_fn_factory(bm25_store)
    # dense may fail if Qdrant not configured
    try:
        dense_fn = _dense_fn_wrapper()
        dense_res = evaluate_retriever(dense_fn, eval_data, k=5)
    except Exception as e:
        print("Dense retriever unavailable:", e)
        dense_res = None

    bm25_res = evaluate_retriever(bm25_fn, eval_data, k=5)

    # hybrid using dense if available
    try:
        hybrid_fn = lambda q, top_k: hybrid_search(q, top_k=top_k, dense_fn=(dense_fn if dense_res else None), bm25_fn=bm25_fn)
        hybrid_res = evaluate_retriever(hybrid_fn, eval_data, k=5)
    except Exception as e:
        print("Hybrid evaluation failed:", e)
        hybrid_res = None

    # Print table
    lines = []
    lines.append("Method | Hit Rate@5 | MRR | n")
    lines.append("---|---:|---:|---")
    if dense_res:
        lines.append(f"dense | {dense_res['hit_rate']:.3f} | {dense_res['mrr']:.3f} | {dense_res['n']}")
    else:
        lines.append("dense | N/A | N/A | 0")
    lines.append(f"bm25 | {bm25_res['hit_rate']:.3f} | {bm25_res['mrr']:.3f} | {bm25_res['n']}")
    if hybrid_res:
        lines.append(f"hybrid | {hybrid_res['hit_rate']:.3f} | {hybrid_res['mrr']:.3f} | {hybrid_res['n']}")
    else:
        lines.append("hybrid | N/A | N/A | 0")

    out = "\n".join(lines)
    print(out)

    # Write docs
    docp = Path("docs/retrieval_evaluation_results.md")
    docp.parent.mkdir(parents=True, exist_ok=True)
    docp.write_text("""# Retrieval evaluation results

Generated by `scripts/run_retrieval_eval.py`.

""" + out)


if __name__ == "__main__":
    main()
